class TestNoiseFilter(unittest.TestCase):
    def test_r1_path_ignore(self):
        self.assertTrue(IGNORE_PATH_RE.search("src/tests/foo.py"))
        self.assertTrue(IGNORE_PATH_RE.search("node_modules/x/index.js"))
        self.assertFalse(IGNORE_PATH_RE.search("src/app.py"))

    def test_r2_generated(self):
        f = classify_finding(
            {"path": "src/x.py", "line": 1, "severity": "ERROR",
             "code": "// auto-generated by protoc-gen-x"}, None)
        self.assertEqual(f["decision"], "IGNORE")

    def test_r3_severity_floor(self):
        f = classify_finding(
            {"path": "src/x.py", "line": 1, "severity": "INFO", "code": "x"})
        self.assertEqual(f["decision"], "STATIC_ONLY")

    def test_r4_snake_case_source_token(self):
        # underscores previously broke \b word-boundary matching
        self.assertTrue(SOURCE_TOKENS.search("open(user_input)"))
        self.assertTrue(SOURCE_TOKENS.search("subprocess.run(req_data, shell=True)"))
        self.assertFalse(SOURCE_TOKENS.search("echo output"))

    def test_r5_sanitizer_hint(self):
        self.assertTrue(SANITIZER_TOKENS.search("return html.escape(x)"))
        self.assertTrue(SANITIZER_TOKENS.search("shlex.quote(x)"))

    def test_r6_family_dedupe(self):
        raw = [
            {"path": "app.py", "line": 26, "severity": "ERROR",
             "vuln_class": "command_injection", "code": "subprocess.run(x, shell=True)"},
            {"path": "app.py", "line": 26, "severity": "ERROR",
             "vuln_class": "subprocess_shell_true", "code": "subprocess.run(x, shell=True)"},
            {"path": "app.py", "line": 33, "severity": "ERROR",
             "vuln_class": "path_traversal", "code": "open(user_input)"},
        ]
        t = triage(raw)
        self.assertEqual(len(t["poc_candidates"]), 2)  # cmd dup merged, traversal kept

    def test_family_map(self):
        self.assertEqual(CLASS_FAMILIES["subprocess_shell_true"], "command_exec")
        self.assertEqual(_family("subprocess_shell_true"), "command_exec")
        self.assertEqual(_family("unknown_class"), "unknown_class")


class TestHarness(unittest.TestCase):
    def _lines(self, rel):
        return os.path.join(APP_VULN, rel)

    def test_line_to_function_mapping(self):
        # fixture: run_cmd_safe ~18-21, run_cmd ~24-27, run_cmd_popen ~30-33,
        # read_note ~35-39 — each sink must map to its own function
        src = open(self._lines("vulnapp.py")).read()
        for line, expect in ((20, "run_cmd_safe"), (26, "run_cmd"),
                             (32, "run_cmd_popen"), (37, "read_note")):
            h, desc = build_harness(
                {"path": "vulnapp.py", "line": line}, APP_VULN, "x")
            self.assertIsNotNone(h, desc)
            self.assertIn(expect, desc, f"line {line} mapped wrong")

    def test_function_hint_anchoring(self):
        h, desc = build_harness(
            {"path": "vulnapp.py", "line": 9999}, APP_FIXED, "x",
            function_hint="read_note")
        self.assertIsNotNone(h, desc)
        self.assertIn("read_note", desc)

    def test_function_hint_missing(self):
        h, desc = build_harness(
            {"path": "vulnapp.py", "line": 1}, APP_FIXED, "x",
            function_hint="nope_fn")
        self.assertIsNone(h)
        self.assertIn("not found", desc)


