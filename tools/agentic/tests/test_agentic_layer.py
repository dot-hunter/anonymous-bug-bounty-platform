class TestSandbox(unittest.TestCase):
    def test_detect_backend(self):
        info = detect_backend("jail")
        self.assertEqual(info["backend"], "jail")
        self.assertTrue(info["available"])

    def test_run_in_sandbox(self):
        r = run_in_sandbox([sys.executable, "-c", "print('OK')"], timeout=15,
                           backend="jail")
        self.assertEqual(r["exit"], 0)
        self.assertIn("OK", r["stdout"])

    def test_network_blocked(self):
        r = run_in_sandbox(
            [sys.executable, "-c",
             "import socket; s=socket.socket(); print('NOPE')"],
            timeout=15, backend="jail")
        self.assertNotEqual(r["exit"], 0)
        self.assertNotIn("NOPE", r["stdout"])


class TestAgenticAuditUnits(unittest.TestCase):
    def test_class_from_check(self):
        # subprocess-shell-true is family-mapped (command_exec) downstream
        self.assertEqual(_class_from_check("python.lang.security.audit.subprocess-shell-true", {}),
                         "subprocess_shell_true")
        self.assertEqual(_class_from_check("foo.command-injection", {}), "command_injection")
        self.assertEqual(_class_from_check("foo.path-traversal", {}), "path_traversal")
        self.assertEqual(_class_from_check("xss.evil", {"cwe": ["CWE-79"]}), "xss")

    def test_list_candidate_files(self):
        files = _list_candidate_files(APP_VULN)
        self.assertTrue(any(f.endswith("vulnapp.py") for f in files))
        self.assertTrue(all(f.endswith(tuple(".py .js .go".split())) for f in files))

    def test_fill_snippets(self):
        lines = {"vulnapp.py": ["a", "b", "subprocess.run(x, shell=True)"]}
        raw = [{"path": "vulnapp.py", "line": 3, "code": ""}]
        _fill_snippets(raw, lines)
        self.assertIn("subprocess.run", raw[0]["code"])


class TestEndToEnd(unittest.TestCase):
    """Slow-ish integration: full audit + retest against the fixtures."""

    def test_audit_vulnerable(self):
        from agentic_audit import audit
        res = audit(APP_VULN, sandbox="jail")
        c = res["counts"]
        self.assertEqual(c["confirmed"], 3, res["validated"])
        self.assertEqual(c["blocked"], 1)
        verdicts = {(v["function"], v["validation"]["verdict"])
                    for v in res["validated"]}
        self.assertIn(("run_cmd", "CONFIRMED"), verdicts)
        self.assertIn(("run_cmd_popen", "CONFIRMED"), verdicts)
        self.assertIn(("read_note", "CONFIRMED"), verdicts)
        self.assertIn(("run_cmd_safe", "BLOCKED"), verdicts)

    def test_retest_fixed(self):
        from agentic_audit import audit, retest
        from pathlib import Path
        res = audit(APP_VULN, sandbox="jail")
        report = Path(res["report_dir"]) / "findings.json"
        rt = retest(report, APP_FIXED, "jail")
        self.assertEqual(rt["counts"]["FIXED"], 3, rt["results"])
        self.assertEqual(rt["counts"]["STILL_PRESENT"], 0)


